-- System Foundation Tables
-- 系统基础表：用户、角色、权限及关联表

-- sys_user 系统用户表
CREATE TABLE IF NOT EXISTS sys_user (
    ID TEXT NOT NULL,
    USERNAME TEXT NOT NULL UNIQUE,
    PASSWORD TEXT NOT NULL,
    NICK_NAME TEXT,
    REAL_NAME TEXT,
    EMAIL TEXT,
    PHONE TEXT,
    AVATAR TEXT,
    STATUS TEXT NOT NULL DEFAULT '1',
    DEL_FLAG TEXT DEFAULT '0',
    CREATE_BY TEXT,
    CREATE_DATE TEXT DEFAULT (datetime('now', 'localtime')),
    UPDATE_BY TEXT,
    UPDATE_DATE TEXT DEFAULT (datetime('now', 'localtime')),
    REMARKS TEXT,
    VER_NO INTEGER DEFAULT 0 NOT NULL,
    SYS_CODE TEXT,
    CONSTRAINT PK_SYS_USER PRIMARY KEY (ID)
);

CREATE INDEX IF NOT EXISTS IDX_SYS_USER_USERNAME ON sys_user(USERNAME);
CREATE INDEX IF NOT EXISTS IDX_SYS_USER_STATUS ON sys_user(STATUS);

-- sys_role 系统角色表
CREATE TABLE IF NOT EXISTS sys_role (
    ID TEXT NOT NULL,
    ROLE_CODE TEXT NOT NULL UNIQUE,
    ROLE_NAME TEXT NOT NULL,
    DESCRIPTION TEXT,
    STATUS TEXT NOT NULL DEFAULT '1',
    SORT_ORDER INTEGER DEFAULT 0,
    DEL_FLAG TEXT DEFAULT '0',
    CREATE_BY TEXT,
    CREATE_DATE TEXT DEFAULT (datetime('now', 'localtime')),
    UPDATE_BY TEXT,
    UPDATE_DATE TEXT DEFAULT (datetime('now', 'localtime')),
    REMARKS TEXT,
    VER_NO INTEGER DEFAULT 0 NOT NULL,
    SYS_CODE TEXT,
    CONSTRAINT PK_SYS_ROLE PRIMARY KEY (ID)
);

-- sys_permission 系统权限表
CREATE TABLE IF NOT EXISTS sys_permission (
    ID TEXT NOT NULL,
    PERM_CODE TEXT NOT NULL UNIQUE,
    PERM_NAME TEXT NOT NULL,
    PERM_TYPE TEXT NOT NULL DEFAULT 'BUTTON',
    PARENT_ID TEXT,
    PATH TEXT,
    SORT_ORDER INTEGER DEFAULT 0,
    STATUS TEXT NOT NULL DEFAULT '1',
    DEL_FLAG TEXT DEFAULT '0',
    CREATE_BY TEXT,
    CREATE_DATE TEXT DEFAULT (datetime('now', 'localtime')),
    UPDATE_BY TEXT,
    UPDATE_DATE TEXT DEFAULT (datetime('now', 'localtime')),
    REMARKS TEXT,
    VER_NO INTEGER DEFAULT 0 NOT NULL,
    SYS_CODE TEXT,
    CONSTRAINT PK_SYS_PERMISSION PRIMARY KEY (ID)
);

CREATE INDEX IF NOT EXISTS IDX_SYS_PERM_PARENT ON sys_permission(PARENT_ID);

-- sys_user_role 用户角色关联表
CREATE TABLE IF NOT EXISTS sys_user_role (
    ID TEXT NOT NULL,
    USER_ID TEXT NOT NULL,
    ROLE_ID TEXT NOT NULL,
    CREATE_BY TEXT,
    CREATE_DATE TEXT DEFAULT (datetime('now', 'localtime')),
    CONSTRAINT PK_SYS_USER_ROLE PRIMARY KEY (ID)
);

CREATE INDEX IF NOT EXISTS IDX_SYS_UR_USER ON sys_user_role(USER_ID);
CREATE INDEX IF NOT EXISTS IDX_SYS_UR_ROLE ON sys_user_role(ROLE_ID);

-- sys_role_permission 角色权限关联表
CREATE TABLE IF NOT EXISTS sys_role_permission (
    ID TEXT NOT NULL,
    ROLE_ID TEXT NOT NULL,
    PERMISSION_ID TEXT NOT NULL,
    CREATE_BY TEXT,
    CREATE_DATE TEXT DEFAULT (datetime('now', 'localtime')),
    CONSTRAINT PK_SYS_ROLE_PERMISSION PRIMARY KEY (ID)
);

CREATE INDEX IF NOT EXISTS IDX_SYS_RP_ROLE ON sys_role_permission(ROLE_ID);
CREATE INDEX IF NOT EXISTS IDX_SYS_RP_PERM ON sys_role_permission(PERMISSION_ID);

