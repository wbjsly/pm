    RISK_ID TEXT NOT NULL,
    MONITOR_DATE TEXT NOT NULL,
    CURRENT_STATUS TEXT NOT NULL,
    STATUS_TREND TEXT,
    NEW_TRIGGERS TEXT,
    NOTES TEXT,
    MONITORED_BY TEXT NOT NULL,
    CREATE_BY TEXT,
    CREATE_DATE TEXT DEFAULT (datetime('now', 'localtime')),
    UPDATE_BY TEXT,
    UPDATE_DATE TEXT DEFAULT (datetime('now', 'localtime')),
    REMARKS TEXT,
    DEL_FLAG TEXT DEFAULT '0',
    VER_NO INTEGER DEFAULT 0 NOT NULL,
    SYS_CODE TEXT,
    CONSTRAINT PK_PM_RISK_MONITOR PRIMARY KEY (ID)
);

CREATE INDEX IF NOT EXISTS IDX_RM_RMON_PROJECT ON pm_risk_monitor(PROJECT_ID);
